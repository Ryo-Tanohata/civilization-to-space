        /// <summary>
        /// 色指数B−Vから星の色を決める。
        ///
        /// 温度から厳密に出しているのではなく、**見た目のための当てはめ**である。
        /// B−Vが小さいほど青白く、大きいほど橙へ寄せている。
        /// おおよその目安: リゲル -0.03、ベガ 0.00、太陽 0.65、ベテルギウス 1.85。
        /// </summary>
        public static Color ColorFor(float bv)
        {
            if (bv < 0.0f)
            {
                return Color.Lerp(new Color(0.62f, 0.74f, 1.00f),
                    new Color(0.85f, 0.90f, 1.00f), Mathf.InverseLerp(-0.4f, 0.0f, bv));
            }

            if (bv < 0.6f)
            {
                return Color.Lerp(new Color(0.85f, 0.90f, 1.00f),
                    new Color(1.00f, 0.98f, 0.92f), Mathf.InverseLerp(0.0f, 0.6f, bv));
            }

            if (bv < 1.1f)
            {
                return Color.Lerp(new Color(1.00f, 0.98f, 0.92f),
                    new Color(1.00f, 0.86f, 0.66f), Mathf.InverseLerp(0.6f, 1.1f, bv));
            }

            return Color.Lerp(new Color(1.00f, 0.86f, 0.66f),
                new Color(1.00f, 0.72f, 0.52f), Mathf.InverseLerp(1.1f, 2.0f, bv));
        }

        /// <summary>赤経・赤緯（度）から、半径1の球の上の向きを出す。</summary>
        public static Vector3 Direction(float raDegrees, float decDegrees)
        {
            var r = raDegrees * Mathf.Deg2Rad;
            var d = decDegrees * Mathf.Deg2Rad;
            var cos = Mathf.Cos(d);
            return new Vector3(cos * Mathf.Cos(r), Mathf.Sin(d), cos * Mathf.Sin(r));
        }
